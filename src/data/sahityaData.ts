/**
 * Deterministic Poem of the Day algorithm:
 * Uses the day of the year and year to choose a poem so it rotates every single day
 * automatically in 2026, 2027, 2028 and beyond!
 */
export const getPoemOfTheDay = (dayOfYear: number, year: number): PoemEntry => {
  const index = (dayOfYear + year * 7) % classicPoems.length;
  return classicPoems[index];
};

